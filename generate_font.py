keys = sorted(ICONS.keys())
num_icons = len(keys)
img = Image.new("RGBA", (16 * num_icons, 16), (0, 0, 0, 0))
pixels = img.load()

for idx, k in enumerate(keys):
    grid = ICONS[k]
    ox = idx * 16
    for y in range(16):
        row = grid[y]
        for x in range(16):
            if row[x] == "1":
                pixels[ox + x, y] = (255, 255, 255, 255)

img.save("garmin_icons.png")

